def build_case_118ww(n_segments: int = 3) -> CaseMPC:
    mpc = CaseMPC()

    mpc.buses = [
        BusData(
            bus_i=bi,
            bus_type=bt,
            Pd=pd,
            Qd=qd,
            Vm=1.0,
            Va=0.0,
            baseKV=138.0,
            Vmax=1.06,
            Vmin=0.94,
        )
        for bi, bt, pd, qd in CASE118_BUSES
    ]

    mpc.generators = []
    for row in CASE118_FOSSIL_UNITS:
        (
            _unit_id, bus, pmin, pmax, qmin, qmax, ton, toff,
            _rup, _rdn, *_rest,
        ) = row
        mpc.generators.append(
            GenData(
                bus=int(bus),
                Pg=0.0,
                Pmax=float(pmax),
                Pmin=float(pmin),
                Qmax=float(qmax),
                Qmin=float(qmin),
                T_on_min=int(ton),
                T_off_min=int(toff),
            )
        )

    mpc.gen_costs = []
    for row in CASE118_FOSSIL_UNITS:
        (
            _unit_id, _bus, _pmin, _pmax, _qmin, _qmax, _ton, _toff,
            rup, rdn, _qsc, _msr, _init_time, startup_fuel, _fuel_type,
            _source_fuel_price, _emission_coef, ca, cb, cc,
        ) = row
        mpc.gen_costs.append(
            GenCostData(
                model=2,
                cost_a=float(ca),
                cost_b=float(cb),
                cost_c=float(cc),
                ramp_up=float(rup),
                ramp_down=float(rdn),
                fuel_price=3.0,
                startup_fuel=float(startup_fuel),
                shutdown_fuel=0.25 * float(startup_fuel),
            )
        )

    if len(CASE118_BRANCH_RATEA) != len(CASE118_RAW_BRANCH):
        raise ValueError("CASE118_BRANCH_RATEA length must match CASE118_RAW_BRANCH")

    mpc.branches = [
        BranchData(
            int(fbus),
            int(tbus),
            float(r),
            float(x),
            float(b),
            float(CASE118_BRANCH_RATEA[l]),
        )
        for l, (fbus, tbus, r, x, b, _) in enumerate(CASE118_RAW_BRANCH)
    ]

    mpc.NB = len(mpc.buses)
    mpc.NG = len(mpc.generators)
    mpc.NL = len(mpc.branches)
    build_load_profile(mpc)
    build_ptdf(mpc)
    derive_piecewise_costs(mpc, n_segments=n_segments)
    return mpc


